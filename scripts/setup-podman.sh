#!/usr/bin/env bash
# System-wide Podman from Alvistack OBS, restricted to an explicit package list.
# Run: sudo bash scripts/setup-podman.sh
set -euo pipefail

if [[ $EUID -ne 0 ]]; then
  echo 'Run with sudo: sudo bash scripts/setup-podman.sh' >&2
  exit 1
fi
# These Ubuntu packages overlap Alvistack's containers-common, whose metadata
# does not declare the replacement. APT simulations cannot detect file collisions.
for old_package in golang-github-containers-common golang-github-containers-image; do
  if [[ $(dpkg-query -W -f='${db:Status-Status}' "$old_package" 2>/dev/null || true) == installed ]]; then
    echo "Conflicting Ubuntu package installed: $old_package" >&2
    echo 'Stop: review the configuration-package migration in README.md before proceeding.' >&2
    exit 1
  fi
done
source /etc/os-release
if [[ ${UBUNTU_CODENAME:-${VERSION_CODENAME:-}} != noble ]] || [[ $(dpkg --print-architecture) != amd64 ]]; then
  echo 'This script is reviewed only for Ubuntu/Pop!_OS 24.04 (noble), amd64.' >&2
  exit 1
fi
for command in curl gpg apt-get apt-cache install; do
  command -v "$command" >/dev/null || { echo "Missing prerequisite: $command" >&2; exit 1; }
done

# Use the direct content endpoint: the mirror redirector can serve stale .debs
# whose sizes/checksums differ from the current signed index.
repo='https://downloadcontent.opensuse.org/repositories/home:/alvistack/xUbuntu_24.04/'
fingerprint='789CFFDE0295B8A1F4E5690C4BECC97550D0B1FD'
keyring='/etc/apt/keyrings/alvistack-podman.gpg'
source_file='/etc/apt/sources.list.d/alvistack-podman.sources'
pin_file='/etc/apt/preferences.d/alvistack-podman'
tmp=$(mktemp -d)
trap 'rm -rf -- "$tmp"' EXIT
mkdir -m 700 "$tmp/gnupg"

curl --fail --silent --show-error --location --max-time 60 "${repo}Release.key" -o "$tmp/Release.key"
actual=$(gpg --homedir "$tmp/gnupg" --batch --show-keys --with-colons "$tmp/Release.key" | awk -F: '$1 == "fpr" { print $10; exit }')
if [[ $actual != "$fingerprint" ]]; then
  echo "Repository signing key changed; stop and review. Received fingerprint: $actual" >&2
  exit 1
fi
gpg --homedir "$tmp/gnupg" --batch --dearmor --output "$tmp/keyring.gpg" "$tmp/Release.key"

printf '%s\n' \
  'Types: deb' \
  "URIs: $repo" \
  'Suites: /' \
  'Architectures: amd64' \
  "Signed-By: $keyring" > "$tmp/source"
printf '%s\n' \
  'Package: podman buildah containers-common containers-storage podman-aardvark-dns podman-netavark skopeo crun conmon catatonit passt' \
  'Pin: release o=obs://build.opensuse.org/home:alvistack/xUbuntu_24.04' \
  'Pin-Priority: 600' \
  '' \
  'Package: *' \
  'Pin: release o=obs://build.opensuse.org/home:alvistack/xUbuntu_24.04' \
  'Pin-Priority: -1' > "$tmp/pin"

# Permit only the exact source file generated by the previous script to migrate.
legacy_source=$(<"$tmp/source")
printf '%s\n' "${legacy_source//downloadcontent.opensuse.org/download.opensuse.org}" > "$tmp/legacy-source"

# Never silently replace previously customized configuration.
for mapping in "keyring.gpg:$keyring" "source:$source_file" "pin:$pin_file"; do
  input=${mapping%%:*}
  output=${mapping#*:}
  if [[ -e $output ]] && ! cmp -s "$tmp/$input" "$output"; then
    if [[ $input == source ]] && cmp -s "$tmp/legacy-source" "$output"; then
      echo 'Migrating the existing repository URL to the direct content endpoint.'
    else
      echo "Existing file differs; review it manually before proceeding: $output" >&2
      exit 1
    fi
  fi
done
install -d -m 0755 /etc/apt/keyrings
install -m 0644 "$tmp/keyring.gpg" "$keyring"
install -m 0644 "$tmp/source" "$source_file"
install -m 0644 "$tmp/pin" "$pin_file"

echo 'Repository configured. APT will verify its signed metadata.'
apt-get update
apt-cache policy podman skopeo crun
packages=(podman crun conmon catatonit passt uidmap fuse-overlayfs)
LC_ALL=C apt-get --simulate --no-install-recommends install "${packages[@]}" | tee "$tmp/plan"
if grep -q '^Remv ' "$tmp/plan"; then
  echo 'Refusing a plan that removes installed packages. Review manually.' >&2
  exit 1
fi

echo
echo 'Review the plan above. The install command below also asks for confirmation.'
echo 'If you decline, the repository configuration remains installed.'
echo 'This repository uses epoch 100:; returning to Ubuntu packages needs an explicit downgrade.'
apt-get --no-remove --no-install-recommends install "${packages[@]}"
podman --version
printf '\nNow test as your normal user (not sudo):\n  podman info\n  podman run --rm docker.io/library/alpine:latest echo "Podman works"\n'
